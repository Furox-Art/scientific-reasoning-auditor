def canonical_hash(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                     allow_nan=False, separators=(',', ':')).encode('utf-8')).hexdigest()


def criteria_catalog():
    """Return detached JSON data; mutation never changes the catalog or its hash."""
    result = {'schema_version': 'scientific-criteria-catalog/1.0',
              'scope': 'Original extensible review catalog; not exhaustive or official guideline certification.',
              'support_levels': list(SUPPORT_LEVELS), 'applicability_states': list(APPLICABILITY),
              'execution_states': list(EXECUTION_STATES),
              'criteria': json.loads(json.dumps([asdict(row) for row in CATALOG]))}
    result['catalog_sha256'] = canonical_hash(result)
    return result
