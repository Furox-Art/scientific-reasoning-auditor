"""Original, extensible manuscript-review questions; not an official checklist."""
from dataclasses import asdict, dataclass
import hashlib
import json

STUDY_TYPES = ('unknown', 'quantitative', 'qualitative', 'computational',
               'theoretical', 'systematic-review', 'narrative-review', 'mixed')
SUPPORT_LEVELS = ('structured_checks', 'screening_only', 'human_review_only', 'not_implemented')
APPLICABILITY = ('applicable', 'requires_review', 'not_applicable')
EXECUTION_STATES = ('checks_completed', 'screening_completed', 'partial', 'failed',
                    'unavailable', 'not_requested', 'human_review_required',
                    'not_implemented', 'not_applicable')
EMPIRICAL = ('quantitative', 'qualitative', 'computational')
NUMERIC = ('quantitative', 'computational', 'systematic-review')


@dataclass(frozen=True)
class Criterion:
    id: str
    title: str
    required_evidence: tuple[str, ...]
    procedure: str
    limitation: str
    support_level: str = 'human_review_only'
    study_types: tuple[str, ...] = ()
    conditional: bool = False
    toolkit_checks: tuple[str, ...] = ()
    modules: tuple[str, ...] = ()
    profile_rules: tuple[str, ...] = ()
    scientific_checks: tuple[str, ...] = ()


